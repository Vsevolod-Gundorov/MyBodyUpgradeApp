/* ---------- оценка рабочего веса под конкретного атлета ---------- */
// Процент от 1ПМ, который можно поднять на reps повторов (Эпли, обратная формула),
// со скидкой на запас (RIR): каждый «оставленный в баке» повтор ≈ −3% веса.
export function pctOf1RM(reps, rir = 1) {
  const r = Math.max(1, Math.min(30, reps || 1));
  const base = 1 / (1 + r / 30);
  return base * (1 - 0.03 * Math.max(0, rir));
}
const roundTo = (v, step) => Math.round(v / step) * step;

/**
 * Рабочий вес упражнения под атлета.
 * @param ex     запись пула
 * @param opts   { e1rm: { [movementId|lift]: кг }, baselines, bodyweight, reps: [lo,hi], rir }
 * @returns { lo, hi, est1RM, source: "own"|"estimate"|"none", perHand, bw }
 *   lo/hi — вилка рабочего веса (для bwp — довесок сверх своего веса)
 */
export function workingWeight(ex, opts = {}) {
  if (!ex) return null;
  const { e1rm = {}, baselines = {}, bodyweight = 90, reps = [8, 10], rir = 1 } = opts;
  const step = EQUIP_STEP[ex.equip] || 2.5;
  // 1) свой замер по этому движению — самый точный источник
  const ownKey = ex.lift || ex.id;
  let est = e1rm[ownKey] || 0;
  let source = est > 0 ? "own" : "none";
  // 2) иначе — оценка от базового лифта через коэффициент
  if (!est) {
    const refKey = ex.ref || "bench";
    const refVal = e1rm[refKey] || baselines[refKey] || 0;
    if (refVal > 0 && ex.k) { est = refVal * ex.k; source = "estimate"; }
  }
  if (!est) return { lo: 0, hi: 0, est1RM: 0, source: "none", perHand: !!ex.perHand, bw: !!ex.bw };
  // собственный вес входит в систему — вычитаем его из результата
  const hi1 = est * pctOf1RM(reps[0], rir);
  const lo1 = est * pctOf1RM(reps[1], rir);
  let lo = lo1, hi = hi1;
  if (ex.bw) { lo = lo1 - bodyweight; hi = hi1 - bodyweight; }
  if (ex.perHand) { lo /= 2; hi /= 2; }
  lo = Math.max(0, roundTo(lo, step));
  hi = Math.max(lo, roundTo(hi, step));
  return { lo, hi, est1RM: est, source, perHand: !!ex.perHand, bw: !!ex.bw };
}

/** Подсказка «чем заменить»: то же основное движение, тот же паттерн или та же группа. */
export function similarTo(id, limit = 12) {
  const ex = exById(id);
  if (!ex) return [];
  return EXERCISES
    .filter((x) => x.id !== id)
    .map((x) => {
      let score = 0;
      if (x.pattern === ex.pattern) score += 3;
      if (x.group === ex.group) score += 3;
      if ((ex.also || []).includes(x.group) || (x.also || []).includes(ex.group)) score += 1;
      if (x.tier === ex.tier) score += 1;
      return { x, score };
    })
    .filter((r) => r.score >= 3)
    .sort((a, b) => b.score - a.score || a.x.name.localeCompare(b.x.name))
    .slice(0, limit)
    .map((r) => r.x);
}

/**
 * Поиск по арсеналу. Ищем не только по названию: «блок», «грудь», «изоляция» —
 * всё это то, как движение ищут в зале, а не как оно называется в программе.
 * Регистр и раскладка кавычек не важны, пустой запрос возвращает весь пул.
 */
export function searchExercises(query, list = EXERCISES) {
  const q = String(query || "").trim().toLowerCase().replace(/ё/g, "е");
  if (!q) return list.slice();
  const norm = (t) => String(t || "").toLowerCase().replace(/ё/g, "е");
  return list.filter((ex) => [ex.name, ex.short, MUSCLES[ex.group], PATTERNS[ex.pattern], EQUIP[ex.equip]]
    .some((t) => norm(t).includes(q)));
}
