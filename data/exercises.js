// Отсюда собираются квесты (data/program.js) и экран «Арсенал движений».
//
// Поля:
//   id        — стабильный ключ (совпадает с ключом в журнале подходов и аналитике)
//   name      — полное имя, short — короткое для узких мест
//   group     — основная мышечная группа, also — что работает вторично
//   pattern   — двигательный паттерн (покрытие проверяется тестами)
//   equip     — bb | db | machine | cable | bw | bwp (свой вес + довесок)
//   tier      — 1 тяжёлая база (длинный отдых), 2 компаунд, 3 изоляция
//   lift      — базовый лифт для аналитики силы (bench/squat/deadlift/ohp), если это он
//   ref + k   — оценка 1ПМ: est1RM = e1RM(ref) × k. Для db/cable k задан на ОБЕ стороны,
//               perHand делит пополам. Для bwp k считается от полной системы (тело + довесок).
//   stretch   — движение грузит мышцу в растянутой позиции (приоритет по данным 2023–2025)
//   cns       — системная цена движения: 3 — максимальная база (осевая штанга, присед/становая),
//               2 — тяжёлое многосуставное, 1 — многосуставное на тренажёре, 0.5 — изоляция.
//               По ней считается нагрузка квеста и работает правило «одна максимальная база за сессию»
//   desc/cues — что даёт и ключевые точки техники (экран «Арсенал»)

