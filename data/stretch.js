/* ---------- прогрессии из таблицы цикла (недели 1–5) ---------- */
// длинная статика: 60 → 75 → 90 → 90–120 → 60 с (на разгрузке — 70% глубины).
// Поза, у которой в неделю 1 уже 90 с, не укорачивается, а держит своё.
const STATIC = [60, 75, 90, 120, 60];
const staticSec = (base) => STATIC.map((v, i) => (i === 4 ? 60 : Math.max(base, v)));
const secTxt = (s, i) => (i === 3 && s >= 90 ? "90–120 с" : `${s} с`);
const PNF = [2, 2, 3, 3, 1];
const LIFTOFF = ["3 × 3 с", "4 × 3 с", "5 × 4 с", "5 × 5 с", "3 × 3 с"];
const cycles = (n) => `${n} ${n === 1 ? "цикл" : n < 5 ? "цикла" : "циклов"} PNF`;
const fixed = (txt) => [txt, txt, txt, txt, txt];
const yt = (q) => q;   // поиск видео техники на YouTube — по ключевым словам из программы

/**
 * Упражнение: id, name, dose[5] — дозировка по неделям, sec[5] — сколько держать позу
 * (для таймера; нет — таймер не нужен), cues — ключевые моменты, pf — тазовое дно,
 * video — поисковый запрос техники.
 */
const X = (id, name, dose, cues, { sec = null, pf = "", video = "" } = {}) => ({ id, name, dose, sec, cues, pf, video });

const holdStatic = (base, tail = "", side = false) => {
  const s = staticSec(base);
  return { dose: s.map((v, i) => `${secTxt(v, i)}${tail}${side ? " на сторону" : ""}`), sec: s };
};

