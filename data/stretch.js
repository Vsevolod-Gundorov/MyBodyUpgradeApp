/**
 * Неделя программы после тренировки. Неделя засчитана, когда в ней сделаны A и B;
 * после разгрузки — новый цикл с недели 2. Чистая функция: { week, cycle } → { week, cycle }.
 */
export function nextStretchWeek({ week, cycle }, doneInWeek) {
  if (!(doneInWeek.has("A") && doneInWeek.has("B"))) return { week, cycle };
  if (week >= STRETCH_CYCLE_WEEKS) return { week: STRETCH_RESTART_WEEK, cycle: cycle + 1 };
  return { week: week + 1, cycle };
}
